def level_set(G,times,t):
  H = nx.Graph()
  H.add_nodes_from(G)
  n = len(G.nodes)
  edges = list(G.edges)
  on = True
  for i in range(len(edges)):
    ints = times[i+n]
    for j in range(len(ints)):
      if j==len(ints)-1:
        if on and t>ints[j]:
          edge = edges[i]
          H.add_edge(edge[0],edge[1])
      if on and ints[j]<t and ints[j+1]>t:
        edge = edges[i]
        H.add_edge(edge[0],edge[1])
        break
      on = not on
  return H

