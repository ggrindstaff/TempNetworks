"""#Analysis functions

### autocorrelation

We begin with autocorrelation of 1-d time series, and find the autocorrelation of both graph-based and topological statistics

$$ \frac{\sum_t (\gamma_t-\bar{\gamma})(\gamma_{t+\epsilon}-\bar{\gamma})}{\sum_t (\gamma_t - \bar{\gamma})^2}$$

If $\gamma$ doesn't vary, then this is equal to 1. If $\gamma$ alternates with respect to lag $ϵ$, this is -1.
"""

def autocorrelation(gamma,lag=1):
  gamma_bar = sum(gamma)/len(gamma)
  num= 0
  denom=0
  for t in range(len(gamma)-lag):
    num = num + (gamma[t]-gamma_bar)*(gamma[t+lag]-gamma_bar)
    denom = denom + (gamma[t]-gamma_bar)**2
  denom = denom + (gamma[-lag]-gamma_bar)**2
  if denom == 0:
    return 0
  else:
    return num/denom

"""The following function is meant for consecutive shapshots of the same temporal graph; in particular, G and H must have the same nodes. The function compares the adjacency matrices: for each vertex $i$, if any incident edge is present in both graphs (i.e. the network at timestep $t$ and $t+1$), then $\gamma[i]$ is defined to be the fraction of $st(i)$ that is present at both $t$ and $t+1$.

$$ \frac{A_i\cdot B_i}{\sqrt{|A_i||B_i|}}$$
"""

def adjacency_correlation(G,H):
  A = nx.to_numpy_array(G)
  B = nx.to_numpy_array(H)
  n = len(G.nodes)
  gamma = np.zeros(n)
  for i in range(n):
    if np.sqrt(sum(A[i,]))*np.sqrt(sum(B[i,]))==0:
      pass
    else:
      gamma[i] = sum(A[i,]*B[i,])/(np.sqrt(sum(A[i,]))*np.sqrt(sum(B[i,])))
  return sum(gamma)/n

def graph_autocorrelation(G,times, snapshots):
  gamma = [adjacency_correlation(level_set(G,times,snapshots[i]),
                                 level_set(G,times,snapshots[i+1])) for i in range(len(snapshots)-1)]
  return autocorrelation(gamma)

"""### Topological persistence level

Instead of correlating the adjacency matrix, here we investigate the fraction of all features (all dimensions) at timesteps $t_1$ and $t_2$ that persist through the interval $(t_1,t_2)$, expressed as
$$ \frac{f_{12}}{\sqrt{f_1*f_2}} ,$$
where $f_1$ and $f_2$ are the betti numbers at times $t_1$ and $t_2$, respectively, and $f_{12}$ is the dimension of the submodule $PH^{t_1t_2}_{*}(N)$ persisting from $t_1$ to $t_2$.
"""

def dgm_correlation(dgms,t1,t2,format='tuples'):
  f1 = 0
  f2 = 0
  f12 = 0
  if format=='tuples':
    for dgm in dgms:
      for (b,d) in dgm:
        f1 = f1 + int(b<=t1<=d)
        f2 = f2 + int(b<=t2<=d)
        f12 = f12 + int(b<=t1<=d and b<=t2<=d)
  if format=='dionysus':
    for dgm in dgms:
      for p in dgm:
        bi = p.birth
        de = p.death
        f1 = f1 + int(bi<=t1<=de)
        f2 = f2 + int(bi<=t2<=de)
        f12 = f12 + int(bi<=t1<=de and bi<=t2<=de)
  if f1*f2==0:
    return 0
  else: return f12/np.sqrt(f1*f2)

def top_autocorr(dgms,snapshots,lag=1,format='tuples'):
  gamma = [dgm_correlation(dgms,snapshots[i],snapshots[i+1],format) for i in range(len(snapshots)-1)]
  return autocorrelation(gamma,lag)

"""##Stationarity

Next we examine topological stationarity. We test if topological autocorrelation through an interval $(t, t+w)$ depends on $t$, or if it depends only on $w$. We test the three distributions:


1.   $t\sim Unif(0,T)$
2.   $w$ in any distribution (we will integrate out)
3.   diagram autocorrelation $dac$ from $t$ to $t+w$

If $cov(t,dac)=0$, or sufficiently small, then we conclude the network is topologically stationary. If not, then there is a topological trend.




"""

def top_stationarity(dgms,times):
  if type(times)==dict:
    format='tuples'
    T = max([max(ent)[1] for ent in list(times.values())])

  if type(times)==list:
    format='dionysus'
    T = int(np.ceil(np.max(times)))

  runs = 10000
  t = []
  dac = []
  for x in range(runs):
    t.append(np.random.rand()*T)
    w = np.random.exponential(scale=1)
    if t[x]+w > 40:
      w = 40-t[x]
    corr = dgm_correlation(dgms,t[x],t[x]+w,format='dionysus')
    dac.append(corr)

  return np.cov(t,dac)[0,1]

