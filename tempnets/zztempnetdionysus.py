def intersection(all_times):
  if len(all_times)==1:
    return all_times[0]
  list1=all_times[0]
  list2=all_times[1]
  inter_times=[]
  for (t1,t2) in list1:
    for (s1,s2) in list2:
      (u,v) = (t1,t2)
      if u>=s2 or v<=s1:
        inter_bool=False
      else:
        inter_bool=True
        if u<s1:
          u=s1
        if v>s2:
          v=s2
      if inter_bool:
        inter_times.append((u,v))
  if inter_times==[]:
    return []
  new = all_times[2:]
  return intersection(all_times[2:] + [inter_times])

